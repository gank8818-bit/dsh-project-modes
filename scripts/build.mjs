import {readFileSync,writeFileSync,mkdirSync,existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import vm from 'node:vm';
const root=fileURLToPath(new URL('../',import.meta.url));
const pkg=JSON.parse(readFileSync(join(root,'package.json'),'utf8'));
const inputs=['index.js','policy.js','families.js','client.source.js'];
const source=Object.fromEntries(inputs.map(name=>[name,readFileSync(join(root,name),'utf8')]));
new vm.Script(source['client.source.js'],{filename:'client.source.js'});
if(!source['client.source.js'].includes("id:'dsh-project-modes'"))throw new Error('Unexpected client module identifier');
const digest=createHash('sha256').update(JSON.stringify(source)).digest('hex').slice(0,12);
const directory=join(root,'lib',pkg.version+'-'+digest);mkdirSync(directory,{recursive:true});
for(const name of inputs.filter(name=>name!=='client.source.js')){
 const path=join(directory,name);
 if(existsSync(path) && readFileSync(path,'utf8')!==source[name])throw new Error('Refusing to alter an existing immutable runtime');
 writeFileSync(path,source[name]);
}
const client=['// Generated by npm run build from client.source.js.',source['client.source.js']].join(String.fromCharCode(10));
writeFileSync(join(root,'client.js'),client);
const manifest={version:pkg.version,runtime:join(directory,'index.js'),client:join(root,'client.js'),clientSha256:createHash('sha256').update(client).digest('hex'),sourceDigest:digest};
writeFileSync(join(root,'build-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
console.log(JSON.stringify(manifest,null,2));
